class BiblicalResearchOutput(BaseModel):
    """
    Structured research result.

    The contract deliberately distinguishes textual observations,
    interpretive synthesis, theological differences, and ministry
    application rather than presenting interpretation as biblical text.
    """

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    title: str = Field(min_length=1)
    scripture: str = ""
    summary: str = Field(min_length=1)

    observations: list[BiblicalResearchSection] = Field(
        default_factory=list
    )
    interpretation: list[BiblicalResearchSection] = Field(
        default_factory=list
    )
    theological_perspectives: list[
        BiblicalResearchSection
    ] = Field(default_factory=list)
    ministry_application: list[
        BiblicalResearchSection
    ] = Field(default_factory=list)

    cautions: list[str] = Field(default_factory=list)

    @field_validator("cautions")
    @classmethod
    def reject_blank_cautions(
        cls,
        value: list[str],
    ) -> list[str]:
        normalized = []

        for item in value:
            item = item.strip()

            if not item:
                raise ValueError(
                    "Research cautions cannot be blank"
                )

            normalized.append(item)

        return normalized



