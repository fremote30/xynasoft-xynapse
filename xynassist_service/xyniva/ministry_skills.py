class SermonPoint(BaseModel):
    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    title: str = Field(min_length=1, max_length=240)
    content: str = Field(min_length=1)


class SermonGenerateInput(BaseModel):
    """
    Structured input for Sermon Studio generation.

    Defaults intentionally preserve the existing XynaFaith sermon
    request contract so V2 can evolve without breaking V1 clients.
    """

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    input: str = ""
    scripture: str = ""
    denomination: str = "general"
    audience: str = ""
    context: str = ""
    tone: str = "balanced"
    duration: str = "30"

    @model_validator(mode="after")
    def require_topic_or_scripture(self):
        if not self.input and not self.scripture:
            raise ValueError(
                "A sermon topic or scripture is required"
            )

        return self


